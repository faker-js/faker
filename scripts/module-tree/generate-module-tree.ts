import { writeFileSync } from 'node:fs';
import { SyntaxKind } from 'ts-morph';
import { getJsDocs, getSince } from '../apidocs/processing/jsdocs';
import {
  toCamelCase,
  toKebabCase,
  toPascalCase,
} from '../shared/character-case';
import { formatTypescript } from '../shared/format';
import { getPartialProject } from '../shared/project';
import { ImportHelper } from './import-helper';

//#region Config

const scriptPlaceholder = '<<<module>>>';
const scriptCommand = `pnpm run generate:module-tree ${scriptPlaceholder}`;

const autoGeneratedCommentHeader = `/*
 * The class body is automatically generated.
 * Run '${scriptCommand}' to update the methods from their respective files.
 */`;

function patchModuleImports(
  moduleName: string,
  importHelper: ImportHelper,
  fileName: string
) {
  switch (moduleName) {
    case 'finance': {
      importHelper.removeImports('./bitcoin-address', 'BitcoinAddressFamily');
      break;
    }
    case 'helpers': {
      if (fileName === 'module.ts') {
        importHelper.addImports('./_eval', 'fakeEval');
      }
      importHelper.addTypeImports('../../core', 'FakerCore');
      break;
    }
    case 'image': {
      importHelper.addTypeImports('../person', 'SexType');
      importHelper.removeImports('../../faker', 'Faker');
      break;
    }
    case 'location': {
      importHelper.removeImports('../../faker', 'Faker');
      break;
    }
    case 'person': {
      importHelper.removeImports('./sex-type', 'Sex');
      importHelper.removeImports('../../faker', 'Faker');
      break;
    }
    default: {
      break; // All as expected
    }
  }
}

function patchFileName(methodName: string): string {
  return methodName === 'nearbyGPSCoordinate'
    ? 'nearby-gps-coordinate'
    : toKebabCase(methodName);
}

function patchJsDocs(module: string, method: string, jsDocs: string): string {
  if (module === 'helpers') {
    if (method === 'multiple') {
      jsDocs = jsDocs
        .replaceAll('((fakerCore)', '(()')
        .replace('((fakerCore,', '((_,');
    } else if (method === 'uniqueArray') {
      jsDocs = jsDocs.replace(
        'faker.helpers.uniqueArray(faker.word.sample, 3)',
        'faker.helpers.uniqueArray(() => faker.word.sample(), 3)'
      );
    }
  }
  return jsDocs;
}

// #endregion

const project = getPartialProject(['src/modules/**/*.ts']);

const directories = project.getDirectoryOrThrow('src/modules').getDirectories();

const moduleNames = new Set(directories.map((dir) => dir.getBaseName()));
const replacePattern = `\\bfake(${[...moduleNames].map(toPascalCase).join('|')})([A-Z][a-zA-Z0-9]+)\\b`;

export async function generateModuleTree(onlyModule?: string): Promise<void> {
  //#region Modules
  for (const directory of directories) {
    const moduleName = directory.getBaseName();

    if (onlyModule && moduleName !== onlyModule) {
      continue;
    }

    console.log(`Processing module: ${moduleName}`);
    const moduleFiles = directory.getSourceFiles([
      'module.ts',
      'simple-module.ts',
    ]);
    for (const moduleFile of moduleFiles) {
      const header = moduleFile
        .getStatements()[0]
        ?.getLeadingCommentRanges()
        .map((c) => c.getText());

      const importHelper = new ImportHelper();
      importHelper.addImports('../../internal/module-base', 'ModuleBase');
      importHelper.addTypeImports('../../faker', 'Faker');
      importHelper.addTypeImports(
        '../../utils/types',
        'Casing',
        'LengthStrategyType',
        'NumberOrRange'
      );
      importHelper.addTypeImports('../../internal/types', 'LiteralUnion');
      importHelper.addTypeImports(
        '../../distributors/distributor',
        'Distributor'
      );

      const exports: string[] = moduleFile
        .getExportDeclarations()
        .map((exp) => exp.getText());

      if (
        moduleFiles.length === 2 &&
        moduleFile.getBaseName() === 'module.ts'
      ) {
        importHelper.addImports(
          './simple-module',
          `Simple${toPascalCase(moduleName)}Module`
        );
      }

      const typesFile = directory.getSourceFile('_types.ts');
      if (typesFile) {
        const typesToImport = [
          typesFile.getEnums(),
          typesFile.getTypeAliases(),
          typesFile.getInterfaces(),
        ]
          .flat()
          .filter((decl) => decl.isExported())
          .map((decl) => decl.getName());

        if (typesToImport.length > 0) {
          importHelper.addTypeImports('./_types', ...typesToImport);
        }
      }

      const content: string[] = [];
      const classes = moduleFile?.getClasses() ?? [];

      //#region Classes
      for (const cls of classes) {
        content.push(getJsDocs(cls).getText());
        const methods = cls
          .getMethods()
          .map((method) => [method.getName(), method] as const)
          .filter(([name]) => name !== 'fake');

        for (const [methodName, original] of methods) {
          const qualifiedMethodName = toCamelCase(
            'fake',
            moduleName,
            methodName
          );
          const methodFileName = patchFileName(methodName);

          const oldSinces = [
            ...(original.getOverloads()?.map((o) => o.getJsDocs()[0]) ?? []),
            ...original.getJsDocs(),
          ].map((jsDocs) => getSince(jsDocs));
          original.remove();

          const methodFile = directory.getSourceFileOrThrow(
            `${methodFileName}.ts`
          );

          //#region Imports
          importHelper.addImports(`./${methodFileName}`, qualifiedMethodName);

          const typesToImport = [
            methodFile.getEnums(),
            methodFile.getTypeAliases(),
            methodFile.getInterfaces(),
          ]
            .flat()
            .filter((decl) => decl.isExported())
            .map((decl) => decl.getName());

          if (typesToImport.length > 0) {
            importHelper.addTypeImports(
              `./${methodFileName}`,
              ...typesToImport
            );
          }
          //#endregion Imports

          const functions = methodFile
            .getChildrenOfKind(SyntaxKind.FunctionDeclaration)
            .filter((fn) => fn.isExported())
            .filter((fn) => fn.getName() === qualifiedMethodName);

          const parts: string[] = [];

          const restoreFakerTreeInvocations = (
            _: string,
            module: string,
            method: string,
            suffix: string = ''
          ): string =>
            `faker.${toCamelCase(module)}.${toCamelCase(method)}${suffix}`;

          //#region Functions
          for (const [index, child] of functions.entries()) {
            const jsDocs = child.getJsDocs()[0];

            if (child.hasBody()) {
              const params = child
                .getSignature()
                .getParameters()
                .slice(1)
                .map((param) => param.getName());

              child.setBodyText(
                `return ${qualifiedMethodName}(this.fakerCore, ${params.join(', ')});`
              );
            }

            //#region JSDocs
            if (jsDocs) {
              const description = jsDocs
                .getFullText()
                // Param
                .replace(' * @param fakerCore The FakerCore to use.\n', '')
                .replaceAll(/ +\*\n +\*\n/g, ' *\n')
                // Examples
                .replaceAll(
                  new RegExp(
                    `${qualifiedMethodName}\\(fakerCore([A-Z_]*)(?:, ?|(?=\\)))`,
                    'g'
                  ),
                  `faker$1.${moduleName}.${methodName}(`
                )
                // Since
                .replaceAll(
                  / +\* @since (.*)\n/g,
                  (_, since: string) =>
                    ` * @since ${oldSinces[index] ?? since}\n`
                )
                // Experimental
                .replaceAll(' *\n * @experimental\n', '')
                // Default Ref Date
                .replaceAll(
                  /(?<= +\* .*?)\bgetDefaultRefDate\(fakerCore(?:, ?|(?=\)))/g,
                  'faker.defaultRefDate('
                )
                // Method References
                .replaceAll(
                  new RegExp(
                    `${replacePattern}(\\(|,)(?:fakerCore(?:, ?|(?=\\))))?`,
                    'g'
                  ),
                  restoreFakerTreeInvocations
                )
                // Locale Access
                .replaceAll(/\bfakerCore\.locale\b/g, 'faker.definitions');

              parts.push(patchJsDocs(moduleName, methodName, description));
            }
            //#endregion JSDocs

            //#region Signature+Implementation
            const signature = child
              .getSignature()
              .getDeclaration()
              .getText()
              // Adapt signature
              .replace(`export function ${qualifiedMethodName}`, methodName)
              .replace(/\((\n +)?fakerCore: FakerCore,?/, '(')
              // Adapt nested options defaults
              .replaceAll(
                /(?<= +\* .*?)\bgetDefaultRefDate\(fakerCore(?:, ?|(?=\)))/g,
                'faker.defaultRefDate('
              )
              .replaceAll(
                new RegExp(
                  `(?<!return )${replacePattern}(\\(|,)(?:fakerCore(?:, ?|(?=\\))))?`,
                  'g'
                ),
                restoreFakerTreeInvocations
              );

            parts.push(signature);
            //#endregion Signature+Implementation
          }
          //#endregion Functions

          cls.addMember(parts.join('\n'));
        }

        const classBody = cls
          .getText()
          .replace(
            /(Module(?:Base)?) {\n( {2}\/\*\n( +\/?\*[^\n]*\n)+ {3}\*\/\n)?/s,
            '$1 {\n\n' +
              `${autoGeneratedCommentHeader.replace(scriptPlaceholder, moduleName)}\n\n`
          );

        content.push(classBody, '');
      }
      //#endregion Classes

      importHelper.removeUnusedImports(content.join('\n'));
      patchModuleImports(moduleName, importHelper, moduleFile.getBaseName());

      content.unshift(
        ...header,
        importHelper.generateImportStatements(),
        '',
        ...exports,
        ''
      );

      writeFileSync(
        moduleFile.getFilePath(),
        await formatTypescript(content.join('\n')),
        'utf8'
      );
    }
  }
  //#endregion Modules
}
