// Extracted to a constant because the contents must not be formatted by oxfmt
const vitePressInFileOptions = `---
editLink: false
---

`;

/**
 * Writes the api docs page and data for the given modules to the correct location.
 *
 * @param pages The pages to write.
 */
export async function writePages(pages: RawApiDocsPage[]): Promise<void> {
  const registryHints: Record<string, string> = Object.fromEntries(
    pages.flatMap((page) =>
      page.methods.map((method) => [
        method.name,
        `${page.camelTitle}.${method.name}`,
      ])
    )
  );
  await Promise.all(pages.map((page) => writePage(page, registryHints)));
}

/**
 * Writes the api docs page and data for the given module to the correct location.
 *
 * @param page The page to write.
 * @param registryHints Hints for accessing standalone functions via module registry.
 */
async function writePage(
  page: RawApiDocsPage,
  registryHints: Record<string, string> = {}
): Promise<void> {
  try {
    await writePageMarkdown(page);
    await writePageData(page, registryHints);
  } catch (error) {
    throw new Error(`Error writing page ${page.title}`, { cause: error });
  }
}

/**
 * Writes the api docs page for the given module to the correct location.
 *
 * @param page The page to write.
 */
async function writePageMarkdown(page: RawApiDocsPage): Promise<void> {
  const { title, camelTitle, deprecated, description, examples, methods } =
    page;
  // Write api docs page
  let content = `
  <script setup>
  import ApiDocsMethod from '../.vitepress/components/api-docs/method.vue';
  import ${camelTitle} from './${camelTitle}.ts';
  </script>

  <!-- This file is automatically generated. -->
  <!-- Run '${SCRIPT_COMMAND}' to update -->

  # ${title}

  ::: v-pre

  ${
    deprecated == null
      ? ''
      : `<div class="warning custom-block">
           <p class="custom-block-title">Deprecated</p>
           <p>This module is deprecated and will be removed in a future version.</p>
           <span>${deprecated}</span>
         </div>`
  }

  ${adjustUrls(description)}

  ${examples.length === 0 ? '' : `<div class="examples">${await codeGroupToHtml(examples, `${camelTitle}-module`)}</div>`}

  :::

  ${methods
    .map(
      (method) => `
  ## ${method.name}

  <ApiDocsMethod :method="${camelTitle}.${method.name}" v-once />
  `
    )
    .join('')}
  `.replaceAll(/\n +/g, '\n');

  content = vitePressInFileOptions + (await formatMarkdown(content));

  writeFileSync(resolve(FILE_PATH_API_DOCS, `${camelTitle}.md`), content);
}

/**
 * Writes the api docs data for the given module to correct location.
 *
 * @param page The page to write.
 * @param registryHints Hints for accessing standalone functions via module registry.
 */
async function writePageData(
  page: RawApiDocsPage,
  registryHints: Record<string, string> = {}
): Promise<void> {
  const { camelTitle, methods } = page;
  const pageData: Record<string, ApiDocsMethod> = Object.fromEntries(
    await Promise.all(
      methods.map(async (method) => [method.name, await toMethodData(method)])
    )
  );
  const prioritizedRegistryHints = {
    ...registryHints,
    // own module > other modules
    ...Object.fromEntries(
      methods.map((method) => [method.name, `${camelTitle}.${method.name}`])
    ),
    // utils always win
    getDefaultRefDate: 'defaultRefDate',
    setDefaultRefDate: 'setDefaultRefDate',
  };

  const refreshFunctions: Record<string, string> = Object.fromEntries(
    await Promise.all(
      methods.map(async (method) => [
        method.name,
        await toRefreshFunction(method, prioritizedRegistryHints),
      ])
    )
  );

  const content =
    `export default ${JSON.stringify(pageData, undefined, 2)}`.replaceAll(
      /"refresh-([^"-]+)-placeholder"/g,
      (_, name) => refreshFunctions[name]
    );

  writeFileSync(
    resolve(FILE_PATH_API_DOCS, `${camelTitle}.ts`),
    await formatTypescript(content)
  );
}

async function toMethodData(method: RawApiDocsMethod): Promise<ApiDocsMethod> {
  const { name, signatures, source } = method;
  const signatureData = required(signatures.at(-1), 'method signature');
  const {
    deprecated,
    experimental,
    description,
    since,
    parameters,
    remarks,
    returns,
    throws,
    signature,
    examples,
    seeAlsos,
  } = signatureData;
  const { filePath, line } = source;
  let formattedSignature = await formatTypescript(signature);
  formattedSignature = formattedSignature.trim();

  // oxlint-disable-next-line typescript/require-await
  const refresh = async () => ['refresh', name, 'placeholder'];
  // This is a placeholder to be replaced by the actual refresh function code
  // If we put the actual code here, it would be a string and not executable
  refresh.toJSON = () => `refresh-${name}-placeholder`;

  return {
    name,
    description: await mdToHtml(description),
    remark:
      remarks.length === 0 ? undefined : await mdToHtml(remarks.join('\n')),
    parameters: await Promise.all(
      parameters.map(async (param) => ({
        ...param,
        type: renderParameterType(param, name),
        description: await mdToHtml(param.description),
      }))
    ),
    since,
    sourcePath: `${filePath}#L${line}`,
    throws:
      throws.length === 0 ? undefined : await mdToHtml(throws.join('\n'), true),
    returns: returns.text,
    signature: await codeToHtml(formattedSignature),
    examples: await codeGroupToHtml(examples, name),
    refresh,
    experimental,
    deprecated: await mdToHtml(deprecated),
    seeAlsos: await Promise.all(
      seeAlsos.map((seeAlso) => mdToHtml(seeAlso, true))
    ),
  };
}

export async function toRefreshFunction(
  method: RawApiDocsMethod,
  registryHints: Record<string, string> = {}
): Promise<string> {
  const { name, signatures } = method;
  const signatureData = required(signatures.at(-1), 'method signature');
  const { examples } = signatureData;

  const exampleCode = examples.join('\n');
  return await toRefreshableCode(name, exampleCode, registryHints);
}

/**
 * Renders the type of a parameter to HTML. Type values that carry a description
 * (shadow type values, see {@link getShadowTypeDescriptions}) become a popover
 * trigger revealing that description, so the per-value documentation is kept
 * without cluttering the description column.
 *
 * @param parameter The parameter whose type to render.
 * @param methodName The name of the method, used to build unique popover ids.
 */
function renderParameterType(
  parameter: RawApiDocsParameter,
  methodName: string
): string {
  const { type, name } = parameter;
  const idPrefix = toIdSlug(`${methodName}-${name}`);

  const members = type.type === 'union' ? type.types : [type];
  if (members.every((member) => !member.description)) {
    return escapeHtml(type.text);
  }

  return members
    .map((member) => renderTypeMember(member, idPrefix))
    .join(' | ');
}

/**
 * Renders a single type (union member) to HTML, as a popover trigger when it
 * has a description, or as plain escaped text otherwise.
 *
 * @param member The type to render.
 * @param idPrefix The prefix for the popover id, unique per parameter.
 */
function renderTypeMember(member: RawApiDocsType, idPrefix: string): string {
  const text = escapeHtml(member.text);
  if (!member.description) {
    return text;
  }

  const id = `${idPrefix}-${toIdSlug(member.text)}`;
  return (
    `<button type="button" class="shadow-type-value" popovertarget="${id}" style="anchor-name:--${id}">${text}</button>` +
    `<div id="${id}" popover class="shadow-type-popover" style="position-anchor:--${id}">${escapeHtml(member.description)}</div>`
  );
}

/**
 * Escapes a string for safe inclusion in HTML text/attribute content.
 *
 * @param value The string to escape.
 */
function escapeHtml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

/**
 * Turns an arbitrary string into a slug safe for use in html ids and css idents.
 *
 * @param value The string to slugify.
 */
function toIdSlug(value: string): string {
  return value.replaceAll(/[^a-zA-Z0-9]+/g, '-').replaceAll(/^-+|-+$/g, '');
}
